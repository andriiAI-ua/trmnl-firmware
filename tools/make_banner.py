# Make include/own_banner_text.h: the 1-bit image of the banner text.
# The firmware fonts have only Latin-1 characters, so the Ukrainian text is an image.
# 1 bits are text pixels. The first pixel of a row is bit 7 of its first byte (bb_epaper drawSprite).
#
# Run it in the repository root (bash, Git Bash on Windows), with Docker:
#   docker run --rm -v "$PWD:/src" -w /src python:3.11.11-slim-bookworm sh -c \
#     "apt-get update -qq && apt-get install -y -qq fonts-dejavu-core >/dev/null && \
#      pip install -q pillow==11.1.0 && python tools/make_banner.py"
import sys

from PIL import Image, ImageDraw, ImageFont

TEXT = "Міняємо екран, зачекайте…"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE = 30
OUT = "include/own_banner_text.h"

font = ImageFont.truetype(FONT, SIZE)
left, top, right, bottom = font.getbbox(TEXT)
width, height = right - left, bottom - top
image = Image.new("1", (width, height), 0)
ImageDraw.Draw(image).text((-left, -top), TEXT, font=font, fill=1)

pitch = (width + 7) // 8
data = bytearray()
for y in range(height):
    for bx in range(pitch):
        byte = 0
        for bit in range(8):
            x = bx * 8 + bit
            if x < width and image.getpixel((x, y)):
                byte |= 0x80 >> bit
        data.append(byte)

lines = [
    "// Generated by tools/make_banner.py. Do not edit.",
    f"// Text: \"{TEXT}\", DejaVu Sans Bold {SIZE} px.",
    "#pragma once",
    "#include <stdint.h>",
    "",
    f"#define OWN_BANNER_TEXT_W     {width}",
    f"#define OWN_BANNER_TEXT_H     {height}",
    f"#define OWN_BANNER_TEXT_PITCH {pitch}",
    "",
    "static const uint8_t own_banner_text[] = {",
]
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
lines.append("};")
with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{OUT}: {width}x{height}, {len(data)} bytes")
sys.exit(0)
